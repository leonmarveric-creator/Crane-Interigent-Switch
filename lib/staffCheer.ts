/** 5月の第2日曜 (母の日) */
const isMothersDay = (day: string) => {
  if (day.slice(5, 7) !== "05") return false;
  const d = Number(day.slice(8, 10));
  const wd = new Date(`${day}T00:00:00Z`).getUTCDay();
  return wd === 0 && d >= 8 && d <= 14;
};
/** 今日が特別な日ならバナーの内容。ふつうの日は null。 */
export function specialDay(day: string, lang: CheerLang): SpecialDay | null {
  if (isMothersDay(day)) {
    return { emoji: "💐", text: lang === "ja"
      ? "母の日おめでとう、Xiaobo さん！いつも本当にありがとう"
      : "母亲节快乐，Xiaobo！谢谢你一直以来为家里付出的一切" };
  }
  const lunar = LUNAR.find(([d]) => d === day);
  if (lunar) return { emoji: lunar[1], text: lunar[2][idx(lang)] };
  const f = FIXED[day.slice(5)];
  return f ? { emoji: f[0], text: f[1][idx(lang)] } : null;
}

