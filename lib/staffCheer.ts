/**
 * スタッフ画面の「元気が出る言葉」と、ちょっとうれしい仕組み。
 *  - 今日のひとこと: 1年分 (366日) すべて違う言葉。季節・行事に合わせてある
 *  - 「换一句」: 季節ごとの言葉 + いつでも使える言葉 (合わせて 100 以上) から
 *  - 特別な日のバナー: 母の日・春節・中秋節など (旧暦の行事は 2026〜2030 年の表)
 *  - 清掃完了のお祝い: 押すたびにランダム
 *  - 今日の清掃がぜんぶ終わったとき: 日替わり
 *  - がんばり記録のバッジ (今年の清掃回数)
 * [中文, 日本語] のペア。
 */
export type CheerLang = "zh" | "ja";
type Pair = [string, string];
const idx = (l: CheerLang) => (l === "ja" ? 1 : 0);

/* ---------------- 今日のひとこと ---------------- */
const DAYS = 12 * 31;
const flatIndex = (day: string) => {
  const m = Number(day.slice(5, 7)) || 1, d = Number(day.slice(8, 10)) || 1;
  return (m - 1) * 31 + (d - 1);
};
type Season = "spring" | "summer" | "autumn" | "winter";
/** 月 → 季節 (春 3〜5 / 夏 6〜8 / 秋 9〜11 / 冬 12〜2) */
export const seasonOf = (month: number): Season =>
  month >= 3 && month <= 5 ? "spring" : month >= 6 && month <= 8 ? "summer" : month >= 9 && month <= 11 ? "autumn" : "winter";

/**
 * 日付 ("YYYY-MM-DD") の今日のひとこと。
 *  - offset 0: 月日で決まる言葉 (1 年間毎日ちがう・その月の季節や行事に合わせてある)
 *  - offset 1〜 (「换一句」): その季節の言葉 + 季節に関係ない言葉 から順番に。
 *    ほかの月の言葉 (例: 9月に「明日から4月」) は出さない。
 */
export function dailyCheer(day: string, lang: CheerLang, offset = 0): string {
  const m = Number(day.slice(5, 7)) || 1;
  if (offset <= 0) return DAILY_BY_MONTH[m - 1][(Number(day.slice(8, 10)) || 1) - 1][idx(lang)];
  const pool = changePool(m);
  const start = (flatIndex(day) * 7) % pool.length; // 日によって最初の言葉を変える
  return pool[(start + offset - 1) % pool.length][idx(lang)];
}
/** 「换一句」で出る言葉の一覧 (その季節 + 季節に関係ない言葉)。 */
export function changePool(month: number): Pair[] {
  return [...SEASON[seasonOf(month)], ...GENERAL];
}
export const DAILY_COUNT = DAYS;

