export function badgeProgress(count: number): { earned: Badge[]; next: Badge | null; left: number } {
  const earned = BADGES.filter((b) => count >= b.at);
  const next = BADGES.find((b) => count < b.at) ?? null;
  return { earned, next, left: next ? next.at - count : 0 };
}

