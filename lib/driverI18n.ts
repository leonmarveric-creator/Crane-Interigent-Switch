export type T = (ja: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: UiLang): T {
  return (ja, vars) => {
    let s = lang === "zh" ? ZH[ja] ?? ja : ja;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
